class SupportAgent:

    def reset_conversation(self):
        """
        Начинает новое обращение.
        """

        self.history.clear()

        self.context.clear()

    def __init__(self):
        self.client = GigaChat(
            base_url=GIGACHAT_BASE_URL,
            credentials=GIGACHAT_CREDENTIALS,
            scope=GIGACHAT_SCOPE,
        )

        self.history = []

        self.knowledge_base = LocalKnowledgeBase()

        self.context = ConversationContext()

        self.knowledge_base = LocalKnowledgeBase()

        self.file_processor = FileProcessor(self.client)

    def ask(self, user_message: str) -> str:

        # ---------------------------------------------------------
        # 1. Сохраняем сообщение пользователя
        # ---------------------------------------------------------

        self.history.append(
            Messages(
                role=MessagesRole.USER,
                content=user_message,
            )
        )

        # ---------------------------------------------------------
        # 2. Ищем информацию в базе знаний
        # ---------------------------------------------------------

        knowledge_results = self.knowledge_base.search(
            user_message,
            limit=3,
        )

        knowledge_context = ""

        if knowledge_results:

            knowledge_context = "\n\n".join(
                result["content"]
                for result in knowledge_results
            )

            for result in knowledge_results:
                self.context.add_knowledge(
                    result["content"]
                )

        # ---------------------------------------------------------
        # 3. Формируем системный промпт
        # ---------------------------------------------------------

        system_prompt = SYSTEM_PROMPT

        # ---------------------------------------------------------
        # 4. Добавляем структурированное состояние обращения
        # ---------------------------------------------------------

        system_prompt += f"""

    --------------------------------------------------
    СТРУКТУРИРОВАННЫЙ КОНТЕКСТ ОБРАЩЕНИЯ
    --------------------------------------------------

    {self.context.to_prompt()}
    """

        # ---------------------------------------------------------
        # 5. Добавляем найденную информацию из базы знаний
        # ---------------------------------------------------------

        if knowledge_context:
            system_prompt += f"""

    --------------------------------------------------
    ИНФОРМАЦИЯ ИЗ ВНУТРЕННЕЙ БАЗЫ ЗНАНИЙ
    --------------------------------------------------

    {knowledge_context}

    --------------------------------------------------

    Используй эту информацию при подготовке ответа.

    Не выдавай информацию из базы знаний за подтверждённый
    факт конкретной ситуации пользователя, если она не была
    подтверждена самим пользователем.
    """

        # ---------------------------------------------------------
        # 6. Формируем сообщения для GigaChat
        # ---------------------------------------------------------

        messages = [
            Messages(
                role=MessagesRole.SYSTEM,
                content=system_prompt,
            )
        ]

        messages.extend(self.history)

        # ---------------------------------------------------------
        # 7. Отправляем запрос
        # ---------------------------------------------------------

        chat = Chat(
            model=GIGACHAT_MODEL,
            messages=messages,
        )

        response = self.client.chat(chat)

        # ---------------------------------------------------------
        # 8. Получаем ответ
        # ---------------------------------------------------------

        assistant_message = response.choices[0].message.content

        # ---------------------------------------------------------
        # 9. Сохраняем ответ в историю
        # ---------------------------------------------------------

        self.history.append(
            Messages(
                role=MessagesRole.ASSISTANT,
                content=assistant_message,
            )
        )

        return assistant_message

    def get_context(self) -> str:
        return self.context.to_prompt()

    def analyze_file(
        self,
        file_path: str,
        user_message: str,
    ) -> str:

        uploaded = self.file_processor.upload(file_path)

        file_id = uploaded.id_

        extension = file_path.lower().split(".")[-1]

        if extension in {"png", "jpg", "jpeg"}:
            return self.file_processor.analyze_image(
                file_id=file_id,
                user_message=user_message,
                model=GIGACHAT_MODEL,
            )

        return self.file_processor.analyze_document(
            file_id=file_id,
            user_message=user_message,
            model=GIGACHAT_MODEL,
        )